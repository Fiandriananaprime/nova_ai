import { NovaError } from '../utils/errors.js';
import type { SessionStatus } from './persistence.js';

const ALLOWED: Record<SessionStatus, SessionStatus[]> = {
  IDLE: ['ANALYZING_CONTEXT', 'ERROR'],
  ANALYZING_CONTEXT: ['ANALYZING_CONTEXT', 'SENDING_PROMPT', 'ERROR', 'PAUSED'],
  SENDING_PROMPT: ['ANALYZING_CONTEXT', 'WAITING_FOR_RESPONSE', 'ERROR', 'PAUSED'],
  WAITING_FOR_RESPONSE: ['ANALYZING_CONTEXT', 'PARSING_RESPONSE', 'ERROR', 'PAUSED'],
  PARSING_RESPONSE: ['ANALYZING_CONTEXT', 'READING_FILES', 'WAITING_FOR_USER', 'WAITING_FOR_APPROVAL', 'VALIDATING_PATCH', 'DONE', 'ERROR', 'PAUSED'],
  READING_FILES: ['ANALYZING_CONTEXT', 'SENDING_PROMPT', 'ERROR', 'PAUSED'],
  WAITING_FOR_USER: ['ANALYZING_CONTEXT', 'SENDING_PROMPT', 'PAUSED', 'ERROR'],
  VALIDATING_PATCH: ['ANALYZING_CONTEXT', 'PREVIEWING_DIFF', 'ERROR', 'PAUSED'],
  PREVIEWING_DIFF: ['ANALYZING_CONTEXT', 'WAITING_FOR_APPROVAL', 'DONE', 'ERROR', 'PAUSED'],
  WAITING_FOR_APPROVAL: ['ANALYZING_CONTEXT', 'APPLYING_PATCH', 'DONE', 'PAUSED', 'ERROR'],
  APPLYING_PATCH: ['ANALYZING_CONTEXT', 'RUNNING_TESTS', 'RECORDING_HISTORY', 'ERROR'],
  RUNNING_TESTS: ['ANALYZING_CONTEXT', 'RECORDING_HISTORY', 'ERROR'],
  RECORDING_HISTORY: ['ANALYZING_CONTEXT', 'DONE', 'ERROR'],
  DONE: [],
  ERROR: ['ANALYZING_CONTEXT', 'SENDING_PROMPT', 'ERROR'],
  PAUSED: ['ANALYZING_CONTEXT', 'SENDING_PROMPT', 'VALIDATING_PATCH', 'PAUSED', 'ERROR'],
};

export function assertTransition(from: SessionStatus, to: SessionStatus): void {
  if (!ALLOWED[from].includes(to)) {
    throw new NovaError(`Transition d’état invalide : ${from} → ${to}.`, 'SESSION_TRANSITION_INVALID');
  }
}
